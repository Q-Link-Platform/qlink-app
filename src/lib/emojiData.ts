// Helper to filter all emojis with search query
export function searchAllEmojis(query: string): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  
  // Flatten all unique emojis
  const all = Array.from(new Set(EMOJI_CATEGORIES.flatMap((c) => c.emojis)));
  
  // Return matching or relevant emojis
  return all.filter((e) => {
    // Exact or direct query match
    return e.includes(q);
  });
}
